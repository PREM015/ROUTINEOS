/**
 * Map a seed entry onto the Prisma create input.
 *
 * `startDelayDays` is not a column on `HabitDefinition` — it is pack
 * scheduling, not a catalogue suggestion — so it is deliberately dropped here
 * and only the starter-pack seeder reads it.
 */
export function toDefinitionCreateInput(
  seed: HabitDefinitionSeed,
  sortOrder: number
): Prisma.HabitDefinitionCreateInput {
  return {
    slug: seed.slug,
    name: seed.name,
    description: seed.description,
    category: seed.category,
    tier: seed.tier,
    frequencyType: seed.frequencyType ?? 'DAILY',
    frequencyValue: seed.frequencyValue ?? null,
    targetValue: seed.targetValue ?? null,
    unit: seed.unit ?? null,
    targetCount: seed.targetCount ?? null,
    intervalDays: seed.intervalDays ?? null,
    trackingType: seed.trackingType ?? 'BOOLEAN',
    direction: seed.direction ?? 'BUILD',
    timeOfDay: seed.timeOfDay ?? null,
    linkedMetricType: seed.linkedMetricType ?? null,
    icon: seed.icon,
    color: seed.color,
    sortOrder,
    isActive: true,
  };
}
