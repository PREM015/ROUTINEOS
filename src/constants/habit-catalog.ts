/**
 * The shared habit catalogue — seed data.
 *
 * A list of *suggestions*. Nothing here is a user's habit: selecting an entry
 * copies these values onto a personal `Habit` row that the owner is free to
 * edit, and no code path reads this file (or the `HabitDefinition` table it
 * seeds) again after that copy is made.
 *
 * Targets are therefore starting points, not rules. "Daily Steps" suggests
 * 15,000 because that is a reasonable starting number, not because 15,000 is
 * the correct target for everyone — the whole point of `targetValue` living on
 * the personal row is that 12,000, 30 or 8,000 are equally valid answers.
 *
 * Fields follow the schema: `trackingType` defaults to BOOLEAN (a tick),
 * `direction` to BUILD, `frequencyType` to DAILY.
 */

import type { Prisma } from '@/generated/prisma';

